#pragma once
#include <stdint.h>
#include <stddef.h>

// Входящие текстовые сообщения, которые пришли, пока телефон не подключён.
//
// Раньше такое сообщение уходило в bleSendNotify, тот без клиента возвращал
// false, и текст пропадал — а отправитель при этом видел галочку «доставлено»:
// подтверждение по эфиру нода отправляла, не глядя, есть ли кому показать.
//
// Теперь сообщение кладётся сюда и отдаётся телефону после подключения и PIN.
// Буфер кольцевой, записи переменной длины: короткое сообщение занимает
// столько, сколько в нём текста, а не все 85 байт. Когда место кончается,
// вытесняются самые старые — свежие нужнее.

// Готовый пакет RECV_MESSAGE без хвоста возраста — его дописывает inboxFlush().
#define INBOX_MAX_RECORD 96

void inboxInit();
// Положить пакет RECV_MESSAGE. Возвращает число вытесненных старых записей.
uint16_t inboxPush(const uint8_t* bleMsg, size_t len);
bool inboxEmpty();
uint16_t inboxCount();
size_t inboxCapacityBytes();
// Посмотреть самую старую запись: копирует пакет в out и пишет возраст в мс.
// Возвращает длину пакета или 0, если буфер пуст. Запись остаётся на месте,
// пока её не снимет inboxDrop() — так неудачная отправка ничего не теряет.
size_t inboxPeek(uint8_t* out, size_t outSize, uint32_t* ageMs);
void inboxDrop();
