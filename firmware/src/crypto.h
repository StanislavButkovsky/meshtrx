#pragma once
#include <stdint.h>
#include <stddef.h>

// Шифрование эфира общим ключом канала.
//
// Заголовок пакета остаётся открытым: по нему работают ретранслятор
// (дедупликация и TTL) и фильтр «моё или не моё». Шифруется только полезная
// нагрузка — речь, текст, содержимое файла.
//
// К пакету дописывается хвост: эпоха и укороченный код аутентичности.
// Восемь байт на голосовом пакете стоят 7 мс эфира — округление символов LoRa
// таково, что шесть байт тега обходятся не дороже четырёх.
#define CRYPTO_KEY_LEN     32
#define CRYPTO_EPOCH_LEN   2
#define CRYPTO_TAG_LEN     6
#define CRYPTO_OVERHEAD    (CRYPTO_EPOCH_LEN + CRYPTO_TAG_LEN)

// Признак «нагрузка зашифрована» — старший бит поля канала. Каналов 23, под
// номер хватает пяти бит, а отдельного байта в пакете нет.
#define PKT_CH_ENCRYPTED   0x80
#define PKT_CH_MASK        0x7F

void cryptoInit();                       // поднять ключ и эпоху из памяти
bool cryptoHasKey();
bool cryptoSetKeyHex(const char* hex);   // 64 шестнадцатеричных символа
// Кодовое слово группы вместо ключа: из фразы ключ выводится медленным
// преобразованием, одинаково на всех устройствах. Длина ключа на размер пакета
// не влияет — в эфир едут подпись и эпоха, а не ключ, — поэтому укорачивать
// сам ключ смысла нет. Неудобен был ввод, его и упрощаем.
bool cryptoSetPassphrase(const char* phrase);
// Восемь символов — нижняя граница, ниже которой фраза перебирается за
// вечер. Хорошая фраза это несколько слов: её и продиктовать проще.
#define CRYPTO_PASS_MIN 8
void cryptoClearKey();
// Отпечаток ключа для интерфейса: четыре символа, по которым люди сверяют,
// что у всех один ключ, не показывая сам ключ.
const char* cryptoKeyFingerprint();

// Слушать ли открытый эфир, когда ключ задан. По умолчанию нет: иначе одна
// рация без ключа сводит шифрование на нет, а люди считают разговор закрытым.
// Но человек может решить иначе — например, чтобы видеть общий чат посёлка и
// при этом говорить со своими под ключом. Тогда открытые сообщения помечаются,
// чтобы их не путали с защищёнными.
bool cryptoHearsPlaintext();
void cryptoSetHearPlaintext(bool on);

// Зашифровать нагрузку на месте и дописать хвост. Возвращает новую длину
// пакета или исходную, если ключа нет.
int cryptoSeal(uint8_t type, uint8_t channel, const uint8_t* sender, uint8_t seq,
               uint8_t* buf, int len, int headerLen);

// Снять шифрование на месте. Возвращает длину без хвоста, 0 — если пакет не
// зашифрован (обрабатывать как обычный), -1 — если ключ не подошёл.
int cryptoOpen(uint8_t type, uint8_t channel, const uint8_t* sender, uint8_t seq,
               uint8_t* buf, int len, int headerLen);
